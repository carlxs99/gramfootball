import { useSyncExternalStore } from "react";
import { MARKET_I18N } from "./i18n.market";

export const LANGS = [
  { code: "en", label: "English", flag: "🇬🇧" },
  { code: "es", label: "Español", flag: "🇪🇸" },
  { code: "ru", label: "Русский", flag: "🇷🇺" },
  { code: "ar", label: "العربية", flag: "🇸🇦" },
  { code: "hi", label: "हिन्दी", flag: "🇮🇳" },
  { code: "pt", label: "Português", flag: "🇵🇹" },
] as const;

export type Lang = (typeof LANGS)[number]["code"];

const KEY = "gram-football.lang";
const LEGACY_KEY = "mccj.lang";
let current: Lang = "en";
const listeners = new Set<() => void>();

function detect(): Lang {
  if (typeof window === "undefined") return "en";
  // Only an explicit choice changes the language; everything else starts in English.
  const saved = (window.localStorage.getItem(KEY) ?? window.localStorage.getItem(LEGACY_KEY)) as Lang | null;
  if (saved && LANGS.some((l) => l.code === saved)) return saved;
  return "en";
}

export function initLang() {
  const next = detect();
  if (next !== current) {
    current = next;
    listeners.forEach((l) => l());
  }
  applyDir(current);
}

function applyDir(lang: Lang) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function setLang(lang: Lang) {
  current = lang;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(KEY, lang);
    window.localStorage.removeItem(LEGACY_KEY);
  }
  applyDir(lang);
  listeners.forEach((l) => l());
}

export function getLang(): Lang {
  return current;
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, () => "en" as Lang);
}

